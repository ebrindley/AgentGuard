import assert from 'node:assert/strict';
import { dirname, join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';

const plugin = process.argv[2];
const { AgentGuard } = await import(pathToFileURL(plugin).href);
const hooks = await AgentGuard({ directory: process.cwd() });
const args = { command: 'command -v codex claude cursor-agent grok opencode', workdir: process.cwd() };
await hooks['tool.execute.before']({ tool: 'bash' }, { args });
const guarded = args.command;
await hooks['tool.execute.before']({ tool: 'bash' }, { args });
assert.equal(args.command, guarded, 'repeat handling must not multiply Guard prefixes');
const prefix = guarded.slice(0, guarded.indexOf('\n') + 1);
const copied = { command: prefix + prefix + 'pwd', workdir: process.cwd() };
await hooks['tool.execute.before']({ tool: 'bash' }, { args: copied });
assert.equal(copied.command, prefix + 'pwd', 'copied current-release exports collapse');
const oldPrefix = prefix.replace(/\/releases\/[^/]+\/peers/, '/releases/0.0.0-older/peers');
const history = { command: oldPrefix + prefix + 'pwd', workdir: process.cwd() };
await hooks['tool.execute.before']({ tool: 'bash' }, { args: history });
assert.equal(history.command, prefix + 'pwd', 'copied old-release exports become the active export');
const user = { command: "export PATH='/tmp/user-peers':$PATH\npwd", workdir: process.cwd() };
await hooks['tool.execute.before']({ tool: 'bash' }, { args: user });
assert.equal(user.command, prefix + "export PATH='/tmp/user-peers':$PATH\npwd", 'user exports remain intact');
const result = spawnSync('/bin/zsh', ['-c', args.command], { encoding: 'utf8' });
assert.equal(result.status, 0, result.stderr);
const release = dirname(dirname(dirname(plugin)));
assert.deepEqual(result.stdout.trim().split('\n'),
  ['codex', 'claude', 'cursor-agent', 'grok', 'opencode'].map(name => join(release, 'peers', name)));
console.log('ok OpenCode Bash normalizes Guard exports and keeps peer wrappers after shell startup');
